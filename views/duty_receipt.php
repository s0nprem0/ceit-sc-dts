// Function to generate PDF receipt
function generate_receipt_pdf($data) {
    $pdf = new FPDF();
    $pdf->AddPage();
    
    // Set font
    $pdf->SetFont('Arial', 'B', 16);
    
    // Header
    $pdf->Cell(0, 10, 'CEIT-SC Office Duty Receipt', 0, 1, 'C');
    $pdf->Ln(10);
    
    // Receipt details
    $pdf->SetFont('Arial', 'B', 12);
    global $daily_receipt_seq, $receipt_date_code;
    $pdf->Cell(0, 8, 'Receipt #: ' . $receipt_date_code . ' - #' . str_pad($daily_receipt_seq, 4, '0', STR_PAD_LEFT), 0, 1);
    $pdf->Cell(0, 8, 'Date Generated: ' . date('F j, Y g:i A'), 0, 1);
    $pdf->Ln(5);
    
    // Personal Information Section
    $pdf->SetFont('Arial', 'B', 14);
    $pdf->Cell(0, 8, 'Personal Information', 0, 1);
    $pdf->Line(10, $pdf->GetY(), 200, $pdf->GetY());
    $pdf->Ln(5);
    
    $pdf->SetFont('Arial', '', 11);
    $pdf->Cell(50, 6, 'Full Name:', 0, 0);
    $pdf->Cell(0, 6, $data['full_name'], 0, 1);
    
    $pdf->Cell(50, 6, 'Student Number:', 0, 0);
    $pdf->Cell(0, 6, $data['student_number'], 0, 1);
    
    $pdf->Cell(50, 6, 'Committee:', 0, 0);
    $pdf->Cell(0, 6, $data['committee'], 0, 1);
    
    $pdf->Cell(50, 6, 'Position:', 0, 0);
    $pdf->Cell(0, 6, $data['position'], 0, 1);
    
    $pdf->Cell(50, 6, 'Course/Year/Section:', 0, 0);
    $pdf->Cell(0, 6, $data['course_year_section'], 0, 1);
    
    $pdf->Cell(50, 6, 'Age:', 0, 0);
    $pdf->Cell(0, 6, $data['age'] . ' years old', 0, 1);
    
    $pdf->Cell(50, 6, 'Contact Number:', 0, 0);
    $pdf->Cell(0, 6, $data['contact_number'], 0, 1);
    
    $pdf->Cell(50, 6, 'Address:', 0, 0);
    $pdf->MultiCell(0, 6, $data['address'], 0, 1);
    
    $pdf->Ln(5);
    
    // Duty Information Section
    $pdf->SetFont('Arial', 'B', 14);
    $pdf->Cell(0, 8, 'Duty Information', 0, 1);
    $pdf->Line(10, $pdf->GetY(), 200, $pdf->GetY());
    $pdf->Ln(5);
    
    $pdf->SetFont('Arial', '', 11);
    $pdf->Cell(50, 6, 'Duty Date:', 0, 0);
    $pdf->Cell(0, 6, date('F j, Y', strtotime($data['duty_date'])), 0, 1);
    
    $pdf->Cell(50, 6, 'Time In:', 0, 0);
    $pdf->Cell(0, 6, date('g:i A', strtotime($data['time_in'])), 0, 1);
    
    $pdf->Cell(50, 6, 'Time Out:', 0, 0);
    $pdf->Cell(0, 6, date('g:i A', strtotime($data['time_out'])), 0, 1);
    
    $pdf->Cell(50, 6, 'Total Hours:', 0, 0);
    $pdf->SetFont('Arial', 'B', 11);
    $pdf->Cell(0, 6, format_hours_minutes($data['total_hours']), 0, 1);
    
    $pdf->Ln(10);
    
    // Footer
    $pdf->SetFont('Arial', 'I', 10);
    $pdf->Cell(0, 6, 'This receipt was automatically generated by the CEIT-SC Office Duty Tracker system.', 0, 1, 'C');
    $pdf->Cell(0, 6, 'Generated on ' . date('F j, Y \a\t g:i A'), 0, 1, 'C');
    
    // Output PDF
    $filename = 'duty_receipt_' . $data['student_number'] . '_' . date('Y-m-d', strtotime($data['duty_date'])) . '.pdf';
    $pdf->Output('D', $filename);
}

