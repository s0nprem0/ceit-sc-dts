// Compute daily receipt number (resets each duty_date)
function get_daily_receipt_number($duty_date, $log_id) {
    global $conn;
    $stmt = $conn->prepare("SELECT COUNT(*) AS seq FROM duty_logs WHERE duty_date = ? AND status = 'Completed' AND log_id <= ?");
    $stmt->bind_param("si", $duty_date, $log_id);
    $stmt->execute();
    $res = $stmt->get_result();
    $row = $res->fetch_assoc();
    $seq = (int)($row['seq'] ?? 0);
    return max(1, $seq);
}

